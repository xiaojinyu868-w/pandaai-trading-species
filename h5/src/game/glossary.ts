export const TERMS: Record<string, TermDef> = Object.fromEntries(LIST.map((x) => [x.t, x]));

/** 别名 → 正名 */
const ALIAS: Record<string, string> = {};
LIST.forEach((x) => {
  ALIAS[x.t] = x.t;
  x.aka?.forEach((a) => (ALIAS[a] = x.t));
});

const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const KEYS = Object.keys(ALIAS).sort((a, b) => b.length - a.length);
const RE_SRC = KEYS.map(esc).join("|");
const isAscii = (s: string) => /^[\x20-\x7e]+$/.test(s);
const isWordChar = (c: string | undefined) => !!c && /[A-Za-z0-9]/.test(c);

export interface Piece { s: string; term?: string }

/** 把一段文字切成普通片段和术语片段；同一段里每个词只标第一次 */
export function splitTerms(text: string, seen: Set<string> = new Set(), max = 4): Piece[] {
  if (!text) return [];
  const re = new RegExp(RE_SRC, "g");
  const out: Piece[] = [];
  let last = 0;
  let n = 0;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text))) {
    const hit = m[0];
    const key = ALIAS[hit];
    const before = text[m.index - 1];
    const after = text[m.index + hit.length];
    if (isAscii(hit) && (isWordChar(before) || isWordChar(after))) continue;
    if (!key || seen.has(key) || n >= max) continue;
    seen.add(key);
    n++;
    if (m.index > last) out.push({ s: text.slice(last, m.index) });
    out.push({ s: hit, term: key });
    last = m.index + hit.length;
  }
  if (last < text.length) out.push({ s: text.slice(last) });
  return out;
}

